#!/usr/bin/env python3
"""mktitle.py: the title's big letters, GEODE in brick studded with
geodes and RUNNER in ladders (like the word levels), from the engine's
3x5 font, as data for src/title.inc (which makes the geodes twinkle).

    python3 tools/mktitle.py > build/title_px.inc

Each letter pixel is one byte across (4 CG6 pixels) by PX_ROWS rows,
drawn from a pattern.  Public domain (Unlicense)."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'mockups'))
from plat_cg6 import SCHEMES        # noqa: E402

PX_ROWS = 8
LINES = [('GEODE', 10, 0), ('RUNNER', 58, 1)]     # word, top row, pattern
PATTERNS = [
    ["BBBB", "BBBB", "BBBB", "....", "BBBB", "BBBB", "BBBB", "...."],   # brick (courses)
    ["L..L", "LLLL", "L..L", "L..L", "L..L", "LLLL", "L..L", "L..L"],   # ladder
    ["BBBB", "BGGB", "GgGG", "GGGG", "BGgB", "BBGB", "....", "BBBB"],   # a geode in the brick
    ["BBGB", "BBGB", "BGGB", "GGGG", "BGGB", "BBGB", "..G.", "BBBB"],   # ... twinkling
]
STUD = 3            # (a geode in every STUD-th brick pixel, spread about)


def font():
    src = open(os.path.join(HERE, '..', 'engine', 'tools', 'mkfont.py')).read()
    g = {}
    exec(src[src.index('G = {'):src.index('}', src.index('G = {')) + 1], g)
    return g['G']


def main():
    col = SCHEMES['blue']
    f = font()
    print("; generated by tools/mktitle.py: do not edit")
    print("TITLE_PX_ROWS\tequ\t%d" % PX_ROWS)
    print("title_pat:")
    for pat in PATTERNS:
        out = []
        for row in pat:
            b = 0
            for ch in row:
                b = (b << 2) | col[ch]
            out.append("$%02X" % b)
        print("\tfcb\t" + ", ".join(out))
    print("; the letter pixels: the screen offset of each, and its pattern")
    print("title_px:")
    studs = []
    for word, top, pat in LINES:
        x0 = (32 - (len(word) * 4 - 1)) // 2
        for i, ch in enumerate(word):
            rows = f[ch].split()
            for y in range(5):
                for x in range(3):
                    if rows[y][x] == '#':
                        off = (top + y * PX_ROWS) * 32 + x0 + i * 4 + x
                        p = pat
                        if pat == 0 and (x + 2 * y + 3 * i) % STUD == 0:
                            p = 2
                            studs.append(off)
                        print("\tfdb\t%d\n\tfcb\t%d" % (off, p * PX_ROWS))
    print("\tfdb\t$FFFF")
    print("; the geodes, to twinkle")
    print("TITLE_STUDS\tequ\t%d" % len(studs))
    print("title_studs:")
    for off in studs:
        print("\tfdb\t%d" % off)


if __name__ == '__main__':
    main()
