#!/usr/bin/env python3
"""mktiles.py: the game's tile graphics, from the mock-up's art
(mockups/plat_cg6.py: TILES and the blue color scheme), as CG6 bytes.

    python3 tools/mktiles.py > build/tiles.inc

Each tile is 4 pixels (one byte) across by 12 rows: 12 bytes, top row
first, in the order of TILE_ORDER; T_<name> is its number.  Public domain
(Unlicense)."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'mockups'))
from plat_cg6 import TILES, SCHEMES     # noqa: E402

# the game's tiles: air, brick (on its own, on top of brick, under brick),
# stone, ladder, cable, geode, and brick being dug out (or filling in): two
# thirds left, one third
TILE_ORDER = [('AIR', None), ('BRICK', 'B'), ('BRICK_TOP', 'b'), ('BRICK_LOW', 'c'),
              ('STONE', 'S'), ('LADDER', 'H'), ('CABLE', '-'), ('GEODE', 'T'),
              ('DIG1', 'd'), ('DIG2', 'e')]
DIG = {
    'd': ["....", "....", "B..B", "....", "B.BB", "B.BB", "B.BB", "....",
          "....", "....", "....", "...."],
    'e': ["....", "....", "....", "....", "....", "B..B", "BB.B", "....",
          "....", "....", "....", "...."],
}

col = SCHEMES['blue']
print("; generated by tools/mktiles.py from mockups/plat_cg6.py: do not edit")
for i, (name, _) in enumerate(TILE_ORDER):
    print("T_%s\tequ\t%d" % (name, i))
print("tiles:")
for name, key in TILE_ORDER:
    art = DIG[key] if key in DIG else TILES[key] if key else ["...."] * 12
    out = []
    for row in art:
        b = 0
        for ch in row:
            b = (b << 2) | col[ch]
        out.append("$%02X" % b)
    print("\tfcb\t%s\t; %s" % (", ".join(out), name))
